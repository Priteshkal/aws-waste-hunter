"""Generate docs/sample-report.md from clearly fictional data (no real account involved)."""

from __future__ import annotations

from pathlib import Path

from aws_waste_hunter.models import Finding, ScanResult, ScanSummary
from aws_waste_hunter.report import to_markdown

ACCOUNT = "111122223333"  # fictional


